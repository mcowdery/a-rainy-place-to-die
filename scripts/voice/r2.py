"""Voice comparison, round 2: what can be controlled (round2.json): more voices, pauses, pace, emotion, sounds, stress.

    python r2.py voices                       Qwen3-TTS VoiceDesign: voice_takes clips a description -> r2/voices/<id>-<n>.wav
    python r2.py fish|chatterbox|turbo --voice <clip in r2/voices, without .wav>
                                              every item that engine has -> r2/<engine>/<item>.wav

An item's text is a string, or a list of strings and numbers: each string is generated by itself and the numbers are
the seconds of silence between them (each piece's own leading and trailing silence is trimmed first, so the gap is
what was asked for). As an object it carries settings too: {"t": ..., "seed", "exaggeration", "cfg_weight",
"stretch" (speed, pitch kept), "semitones" (pitch, length kept)}.
Each engine loads once and runs in its own venv (r2.sh); Fish runs from its checkout, whose modules this imports.
"""
import argparse
import json
import os
import subprocess
import tempfile
import time
from pathlib import Path

import numpy as np
import soundfile as sf

HERE = Path(__file__).resolve().parent
SPEC = json.loads((HERE / "round2.json").read_text(encoding="utf8"))
OUT = Path(os.environ.get("VOICE_OUT", HERE.parent.parent / "debug-shots" / "voice")) / "r2"


def voices():
    import torch
    from qwen_tts import Qwen3TTSModel

    model = Qwen3TTSModel.from_pretrained("Qwen/Qwen3-TTS-12Hz-1.7B-VoiceDesign", device_map="cuda:0", dtype=torch.bfloat16)
    out = OUT / "voices"
    out.mkdir(parents=True, exist_ok=True)
    for v in SPEC["voices"]:
        for n in range(1, SPEC["voice_takes"] + 1):
            torch.manual_seed(n)
            wavs, sr = model.generate_voice_design(text=SPEC["ref_text"], language=SPEC["language"], instruct=v["instruct"])
            sf.write(out / f"{v['id']}-{n}.wav", wavs[0], sr)
            print("voice", v["id"], n, f"{len(wavs[0]) / sr:.1f}s", flush=True)


def fish(ref):
    import torch
    from fish_speech.models.text2semantic.inference import decode_to_audio, encode_audio, generate_long, init_model, load_codec_model

    ckpt, device, precision = Path("checkpoints/s2-pro"), "cuda", torch.bfloat16
    model, decode_one_token = init_model(ckpt, device, precision, compile=False)
    with torch.device(device):
        model.setup_caches(max_batch_size=1, max_seq_len=model.config.max_seq_len, dtype=next(model.parameters()).dtype)
    codec = load_codec_model(ckpt / "codec.pth", device, precision)
    prompt = [encode_audio(str(ref), codec, device).cpu()]

    def synth(text, seed=42, **_):
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        codes = []
        for r in generate_long(model=model, device=device, decode_one_token=decode_one_token, text=text, num_samples=1,
                               max_new_tokens=0, top_p=0.9, top_k=30, temperature=1.0, compile=False, iterative_prompt=True,
                               chunk_length=300, prompt_text=[SPEC["ref_text"]], prompt_tokens=prompt):
            if r.action == "sample":
                codes.append(r.codes)
        return decode_to_audio(torch.cat(codes, dim=1).to(device), codec).float().cpu().numpy(), codec.sample_rate

    return synth


def chatterbox(ref):
    import torch
    from chatterbox.tts import ChatterboxTTS

    model = ChatterboxTTS.from_pretrained(device="cuda")

    def synth(text, seed=42, exaggeration=0.5, cfg_weight=0.5, **_):
        torch.manual_seed(seed)
        return model.generate(text, audio_prompt_path=str(ref), exaggeration=exaggeration, cfg_weight=cfg_weight)[0].cpu().numpy(), model.sr

    return synth


def turbo(ref):
    import torch
    from chatterbox.tts_turbo import ChatterboxTurboTTS
    from huggingface_hub import snapshot_download

    # Its own from_pretrained insists on a Hugging Face login; the files are public.
    model = ChatterboxTurboTTS.from_local(snapshot_download("ResembleAI/chatterbox-turbo", token=False), "cuda")

    def synth(text, seed=42, **_):
        torch.manual_seed(seed)
        return model.generate(text, audio_prompt_path=str(ref))[0].cpu().numpy(), model.sr

    return synth


def trim(x, sr, floor=0.012, keep=0.03):
    """Without the silence a model leaves before and after a piece (keeping 30 ms of it either side)."""
    loud = np.flatnonzero(np.abs(x) > floor * max(1e-6, np.abs(x).max()) * 4)
    if not len(loud):
        return x
    k = int(keep * sr)
    return x[max(0, loud[0] - k): loud[-1] + k]


def ffmpeg(x, sr, flt):
    with tempfile.TemporaryDirectory() as d:
        a, b = Path(d) / "a.wav", Path(d) / "b.wav"
        sf.write(a, x, sr)
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(a), "-af", flt, "-ar", str(sr), str(b)], check=True)
        return sf.read(b, dtype="float32")[0]


def render(synth, spec):
    opts = dict(spec) if isinstance(spec, dict) else {"t": spec}
    text = opts.pop("t")
    if isinstance(text, str):
        x, sr = synth(text, **opts)
    else:
        parts, sr = [], None
        for piece in text:
            if isinstance(piece, str):
                y, sr = synth(piece, **opts)
                parts.append(trim(np.asarray(y, dtype=np.float32), sr))
            else:
                parts.append(piece)
        x = np.concatenate([np.zeros(int(p * sr), np.float32) if isinstance(p, (int, float)) else p for p in parts])
    x = np.asarray(x, dtype=np.float32)
    if "stretch" in opts:
        x = ffmpeg(x, sr, f"atempo={opts['stretch']}")
    if "semitones" in opts:
        r = 2 ** (opts["semitones"] / 12)
        x = ffmpeg(x, sr, f"asetrate={sr * r:.0f},aresample={sr},atempo={1 / r:.5f}")
    return x, sr


ENGINES = {"fish": fish, "chatterbox": chatterbox, "turbo": turbo}

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("engine", choices=["voices", *ENGINES])
    ap.add_argument("--voice", default="gravel-deep-1")
    ap.add_argument("--only", default="", help="a group id, to redo one group")
    a = ap.parse_args()
    if a.engine == "voices":
        voices()
    else:
        out = OUT / a.engine
        out.mkdir(parents=True, exist_ok=True)
        synth = ENGINES[a.engine]((OUT / "voices" / f"{a.voice}.wav").resolve())
        for g in SPEC["groups"]:
            if a.only and g["id"] != a.only:
                continue
            for item in g["items"]:
                spec = item.get(a.engine, item.get("all"))
                if spec is None:
                    continue
                t = time.time()
                try:
                    x, sr = render(synth, spec)
                    sf.write(out / f"{item['id']}.wav", x, sr)
                    print(a.engine, item["id"], f"{len(x) / sr:.1f}s in {time.time() - t:.1f}s", flush=True)
                except Exception as e:  # one bad item shouldn't lose the rest
                    print(a.engine, item["id"], "FAILED", repr(e)[:300], flush=True)
        (out / "voice.txt").write_text(a.voice)
