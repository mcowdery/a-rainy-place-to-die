"""The voice bench's engine worker: one speech model held loaded, answering the bench's server (bench_server.py).

    python bench_engine.py fish|chatterbox|design <port>

It runs in that engine's own venv (bench_env.sh). "chatterbox" serves both Chatterbox and Chatterbox-Turbo (asked for
by "model"), "design" is Qwen3-TTS VoiceDesign. One request at a time:
    GET  /ping   -> {"ready": true}
    POST /synth  {model, pieces: [text | seconds of silence, ...], voice: {path, text}, seed, opts, stretch, semitones, out}
                 writes the take to `out` (a wav) -> {seconds, sr}
    POST /design {instruct, text, seed, out} -> the same
Each piece is generated by itself, its own silence trimmed, and the pieces joined with the silences asked for.
"""
import json
import sys
import time
import traceback
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path

import numpy as np
import soundfile as sf

from r2 import ffmpeg, trim

ENGINE, PORT = sys.argv[1], int(sys.argv[2])


def load_fish():
    import torch
    from fish_speech.models.text2semantic.inference import decode_to_audio, encode_audio, generate_long, init_model, load_codec_model

    ckpt, device, precision = Path("checkpoints/s2-pro"), "cuda", torch.bfloat16
    model, decode_one_token = init_model(ckpt, device, precision, compile=False)
    with torch.device(device):
        # Its attention cache is sized for the longest text the model takes (32,768 tokens: 12 GB of the card). A line and
        # its voice clip are a few hundred, and with the short cache Chatterbox and Turbo fit beside it.
        # (Set on the config, which the generator reads for every length it works out, its own cache set-up included.)
        model.config.max_seq_len = min(model.config.max_seq_len, 4096)
        model.setup_caches(max_batch_size=1, max_seq_len=model.config.max_seq_len, dtype=next(model.parameters()).dtype)
        model._cache_setup_done = True
    codec = load_codec_model(ckpt / "codec.pth", device, precision)
    prompts = {}

    def synth(model_name, text, voice, seed, opts):
        if voice["path"] not in prompts:
            prompts[voice["path"]] = encode_audio(voice["path"], codec, device).cpu()
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        codes = []
        # Without the clip's own words the model takes no voice from it at all.
        prompt = dict(prompt_text=[voice["text"]], prompt_tokens=[prompts[voice["path"]]]) if voice.get("text") else {}
        for r in generate_long(model=model, device=device, decode_one_token=decode_one_token, text=text, num_samples=1,
                               max_new_tokens=0, top_p=float(opts.get("top_p", 0.9)), top_k=30,
                               temperature=float(opts.get("temperature", 1.0)), compile=False, iterative_prompt=True,
                               chunk_length=300, **prompt):
            if r.action == "sample":
                codes.append(r.codes)
        return decode_to_audio(torch.cat(codes, dim=1).to(device), codec).float().cpu().numpy(), codec.sample_rate

    return synth


def load_chatterbox():
    import torch

    models = {}

    def get(name):
        if name not in models:
            if name == "turbo":
                from chatterbox.tts_turbo import ChatterboxTurboTTS
                from huggingface_hub import snapshot_download
                # Its own from_pretrained insists on a Hugging Face login; the files are public.
                models[name] = ChatterboxTurboTTS.from_local(snapshot_download("ResembleAI/chatterbox-turbo", token=False), "cuda")
            else:
                from chatterbox.tts import ChatterboxTTS
                models[name] = ChatterboxTTS.from_pretrained(device="cuda")
        return models[name]

    get("chatterbox")

    def synth(model_name, text, voice, seed, opts):
        m = get(model_name)
        torch.manual_seed(seed)
        kw = {} if model_name == "turbo" else {k: float(opts[k]) for k in ("exaggeration", "cfg_weight", "temperature") if k in opts}
        return m.generate(text, audio_prompt_path=voice["path"], **kw)[0].cpu().numpy(), m.sr

    return synth


def load_design():
    import torch
    from qwen_tts import Qwen3TTSModel

    model = Qwen3TTSModel.from_pretrained("Qwen/Qwen3-TTS-12Hz-1.7B-VoiceDesign", device_map="cuda:0", dtype=torch.bfloat16)

    def design(instruct, text, seed, language="English"):
        torch.manual_seed(seed)
        wavs, sr = model.generate_voice_design(text=text, language=language, instruct=instruct)
        return wavs[0], sr

    return design


def take(synth, q):
    parts, sr = [], None
    for piece in q["pieces"]:
        if isinstance(piece, str):
            y, sr = synth(q["model"], piece, q["voice"], int(q.get("seed", 42)), q.get("opts", {}))
            parts.append(trim(np.asarray(y, dtype=np.float32), sr) if len(q["pieces"]) > 1 else np.asarray(y, dtype=np.float32))
        else:
            parts.append(float(piece))
    x = np.concatenate([np.zeros(int(p * sr), np.float32) if isinstance(p, float) else p for p in parts])
    if q.get("stretch") and abs(q["stretch"] - 1) > 0.005:
        x = ffmpeg(x, sr, f"atempo={q['stretch']}")
    if q.get("semitones"):
        r = 2 ** (q["semitones"] / 12)
        x = ffmpeg(x, sr, f"asetrate={sr * r:.0f},aresample={sr},atempo={1 / r:.5f}")
    return x, sr


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def send(self, code, obj):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        self.send(200, {"ready": True, "engine": ENGINE})

    def do_POST(self):
        q = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        t = time.time()
        try:
            if self.path == "/design":
                x, sr = RUN(q["instruct"], q["text"], int(q.get("seed", 1)), q.get("language") or "English")
            else:
                x, sr = take(RUN, q)
            Path(q["out"]).parent.mkdir(parents=True, exist_ok=True)
            sf.write(q["out"], x, sr)
            print(ENGINE, Path(q["out"]).name, f"{len(x) / sr:.1f}s in {time.time() - t:.1f}s", flush=True)
            self.send(200, {"seconds": len(x) / sr, "sr": sr, "took": time.time() - t})
        except Exception as e:
            traceback.print_exc()
            self.send(500, {"error": repr(e)[:600]})


if __name__ == "__main__":
    RUN = {"fish": load_fish, "chatterbox": load_chatterbox, "design": load_design}[ENGINE]()
    print(f"READY {ENGINE} on {PORT}", flush=True)
    HTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
